param(
    # Default is beside this script, which is the module. Not a relative guess: this used to say
    # "superintelligence/test-replays", which was correct only while it lived at the repository root
    # AND was launched from there - and the corpus it rebuilt into a second tree when either was not
    # true, silently, because the script reported success either way.
    [string]$Dir = (Join-Path $PSScriptRoot 'test-replays'),
    # Per-FLOOR turn caps, not per-run: a run that descends keeps playing until it dies or runs out
    # of floors, so a small cap can still yield thousands of steps. These are sized for a corpus that
    # is worth watching and still rebuilds in seconds.
    [int]$ShortTurns = 25,
    [int]$MidTurns = 150,
    [int]$LongTurns = 600,
    # How long to spend looking for a run that ends in death rather than a turn limit. Probes run
    # concurrently, so this is a wall-clock budget rather than a number of attempts.
    [int]$DeathProbeSeconds = 20,
    # Ceiling on a single recording's process, so one that stops progressing cannot hang the build.
    [int]$PerFileSeconds = 120,
    # Concurrent recordings. Defaults to two fewer than the machine has logical processors: each is a
    # separate JVM doing a single-threaded simulation, so the only thing being oversubscribed by using
    # every core is the OS itself - and a build that saturates the machine reports a timeout as a
    # failure rather than as slowness.
    [int]$Parallel = 0,
    # Reported, not enforced. A rebuild that blows this is still correct; it just means the corpus
    # wants a smaller budget or a faster machine.
    [int]$BudgetSeconds = 60
)

# Rebuilds the committed replay corpus from the current engine, then proves each file reproduces.
#
# Why a script rather than a note: a corpus regenerated by hand goes stale silently and then fails for
# the wrong reason. Every file here is produced by a command that is written down, so the next engine
# change regenerates it the same way - and the proof step means a fixture that does not reproduce is
# reported here rather than discovered later by someone using it.
#
# The old corpus predated the RNG repair, so those recordings reproduced nothing: they were readable
# but dead, which is the worst state for a fixture to be in.
#
# Everything is concurrent. The first version started a job and immediately waited for it, so the
# whole thing was serial despite looking parallel - sixteen recordings cost sixteen JVM startups in a
# row. A recording is a separate JVM doing a single-threaded simulation and is idle most of its life
# waiting on its own startup, so N of them at once cost about as much wall clock as one. Measured on a
# 20-core machine: 17 recordings, a death probe and their verification in 8.8 seconds, against roughly
# 70 for the serial version - and the verification phase, which used a bare `java` call per file, now
# runs the same way.
#
# Concurrency has one hard requirement, which is that no two processes may share a work directory. The
# game keeps its save files there, so sharing it lets parallel runs corrupt each other - see
# Start-Recording.

$ErrorActionPreference = 'Stop'

# This script lives in the :superintelligence module, and every command below is a gradle task
# addressed from the repository root. Resolved from the script's own location rather than from the
# working directory, which is whatever the caller happened to be in - and which is why the default
# $Dir above cannot be relative either.
$module = $PSScriptRoot
$repo   = Split-Path -Parent $module
Push-Location $repo

$stopwatch = [System.Diagnostics.Stopwatch]::StartNew()

# Fresh classes and a freshly written classpath, deliberately. A stale jar means these files are
# produced by a build that is not the one being tested, and the symptom is a header the reader refuses.
# Compiled classes are used rather than jars because this script writes into the module it is
# regenerating for, and a jar of the same build would be fine but adds a jar step for no gain here.
Write-Host "building classes..."
& ./gradlew :superintelligence:classes -q
if ($LASTEXITCODE -ne 0) { Pop-Location; throw "build failed" }

$cp = (Get-Content (Join-Path $repo 'desktop\build\replay-classpath.txt') -Raw).Trim()
#Prepended, not appended. desktop/build/replay-classpath.txt already names a :superintelligence jar,
#and a jar earlier on the classpath wins over classes compiled afterwards - so appending here made a
#stale jar quietly shadow the build the script had just made, and the corpus was regenerated by code
#that was not the code. It produced recordings in the previous inventory format and the gate then
#reported ten divergences that had nothing to do with the fault under test. Compiled classes first is
#what makes "this script rebuilds with the current source" true rather than merely intended.
#
#The two class directories are the module's own, so they are reached from $module and not from the
#working directory - which is how the previous form wrote them into a second tree.
$classes = Join-Path $module 'build\classes\java\main'
$resources = Join-Path $module 'build\resources\main'
$cp = "$classes;$resources;$cp"
$main = 'com.shatteredpixel.shatteredpixeldungeon.superintelligence.Main'

if ($Parallel -le 0) {
    $Parallel = [Math]::Max(2, (Get-CimInstance Win32_ComputerSystem).NumberOfLogicalProcessors - 2)
}

if (-not (Test-Path $Dir)) { New-Item -ItemType Directory -Path $Dir | Out-Null }

# Old recordings go first, and wholesale. A file the new build cannot reproduce is worse than no file:
# it is listed by the catalog, playable, and quietly wrong. Leaving the previous corpus in place to be
# merged would risk exactly that, so the directory is cleared rather than updated.
Get-ChildItem $Dir -File -Filter *.replay -ErrorAction SilentlyContinue | Remove-Item -Force
$rejected = Join-Path $Dir 'rejected'
if (Test-Path $rejected) { Remove-Item $rejected -Recurse -Force }

$logDir = Join-Path $env:TEMP "spd-corpus-log"
if (Test-Path $logDir) { Remove-Item $logDir -Recurse -Force }
New-Item -ItemType Directory -Path $logDir | Out-Null

# Every process this script starts, so that an error anywhere can clean up.
#
# This exists because an error once did not: the script died on a failed Move-Item with twelve rollout
# JVMs still running and nothing owning them, which looked exactly like a freeze. A recording script
# that can leave a dozen JVMs behind on a typo is worse than one that fails cleanly, so the processes
# are tracked centrally rather than cleaned up by each call site remembering to.
$script:spawned = [System.Collections.ArrayList]::new()

trap {
    foreach ($proc in $script:spawned) {
        try {
            if ($proc -and -not $proc.HasExited) { $proc.Kill() }
        } catch {
            # a process that has already gone is not a failure of the cleanup
        }
    }
    Write-Host ""
    Write-Host "[ERROR] corpus build aborted; every process it started has been killed" -ForegroundColor Red
    # restore the caller's working directory too, so an abort does not leave a shell in the
    # repository root that the caller never asked to be in
    Pop-Location
    # rethrow so the exit code is non-zero rather than the script looking like it succeeded
    break
}

function Start-Recording {
    param([string]$Name, [string]$Hero, [int]$Turns, [string]$Seed, [string]$SaveDir = $Dir)

    $path = Join-Path $SaveDir "$Name.replay"
    $log = Join-Path $logDir "$Name.log"

    # Each recording gets its own --out, and this is not tidiness.
    #
    # Without it every concurrent rollout shares one work directory under the temp root, and that is
    # where the game keeps its save files - bones.dat among them. Sixteen JVMs then read and delete each
    # other's files while they run, which is the same cross-episode contamination RunState exists to stop
    # inside one process, reproduced across processes. It showed up as a recording that would not
    # reproduce and as a seed producing a different run on a second rebuild: same seed, 126 steps one day
    # and 128 the next. Serial builds never saw it, because one recording owns the directory outright.
    $work = Join-Path $logDir "work-$Name"
    if (Test-Path $work) { Remove-Item $work -Recurse -Force }
    New-Item -ItemType Directory -Path $work | Out-Null

    # Start-Process rather than Start-Job: a PowerShell job is another PowerShell process, which costs
    # more to start than the recording it is starting. Redirecting to a file rather than capturing the
    # stream also avoids a deadlock on a full pipe buffer, which is what happens when a process writes
    # more than the reader has drained.
    $proc = Start-Process -FilePath 'java' -PassThru -NoNewWindow `
        -RedirectStandardOutput $log -RedirectStandardError "$log.err" `
        -ArgumentList @('-cp', $cp, $main, 'rollout', '--seed', $Seed, '--hero', $Hero,
                        '--max-turns', "$Turns", '--save', $path, '--out', $work, '--no-color')

    $null = $script:spawned.Add($proc)

    [PSCustomObject]@{
        Name = $Name; Hero = $Hero; Seed = $Seed; Path = $path; Log = $log; Work = $work; Proc = $proc
    }
}

function Complete-Recording {
    param($Job)

    $Job.Proc.WaitForExit($PerFileSeconds * 1000) | Out-Null
    if (-not $Job.Proc.HasExited) {
        # owns a process that stopped progressing; kill it rather than let it hold a slot forever
        $Job.Proc.Kill()
        return [PSCustomObject]@{ Job = $Job; Ok = $false; Reason = "timed out after ${PerFileSeconds}s" }
    }

    $out = (Get-Content $Job.Log -Raw -ErrorAction SilentlyContinue)
    $err = (Get-Content "$($Job.Log).err" -Raw -ErrorAction SilentlyContinue)

    if (-not (Test-Path $Job.Path)) {
        $first = (($out + "`n" + $err) -split "`n" | Where-Object { $_.Trim() } | Select-Object -First 1)
        return [PSCustomObject]@{ Job = $Job; Ok = $false; Reason = "no file; $first" }
    }

    $steps = (Get-Content $Job.Path | Select-String -Pattern '^[A-Z_]+ ').Count
    $termination = '?'
    foreach ($reason in @('DEATH', 'VICTORY', 'TURN_LIMIT', 'STALLED')) {
        if ($out -match "outcome\s+$reason") { $termination = $reason; break }
    }

    if ($termination -eq '?') {
        # Not a cosmetic default. A recording whose outcome cannot be read is not a recording this
        # script understands, and reporting it as a normal episode would hide it.
        return [PSCustomObject]@{ Job = $Job; Ok = $false
            Reason = "wrote a file but reported no outcome; see $($Job.Log)" }
    }

    [PSCustomObject]@{ Job = $Job; Ok = $true; Steps = $steps; Termination = $termination; Output = $out }
}

# HeroClass is WARRIOR MAGE ROGUE HUNTRESS DUELIST CLERIC - there is no THIEF or RANGER, and passing
# one is an IllegalArgumentException that costs a whole recording slot to discover.
$heroes = @('WARRIOR', 'MAGE', 'ROGUE', 'HUNTRESS', 'DUELIST', 'CLERIC')

# The seed is the recording's name, so a file says what it was made from and re-recording it gives the
# same run. A corpus whose seeds are opaque names would be one nobody could extend.
$plan = @()
foreach ($hero in $heroes) {
    $plan += , @("$($hero.ToLower())-short", $hero, $ShortTurns)
}
foreach ($hero in $heroes) {
    $plan += , @("$($hero.ToLower())-mid", $hero, $MidTurns)
}
foreach ($hero in @('WARRIOR', 'MAGE')) {
    $plan += , @("$($hero.ToLower())-long", $hero, $LongTurns)
}
# A second seed per hero for two classes, so the corpus covers "the same hero somewhere else" rather
# than one world per hero class. Replay verification is a claim about determinism, and a single seed
# per class is a thin sample of that claim.
foreach ($hero in @('WARRIOR', 'MAGE')) {
    $plan += , @("$($hero.ToLower())-alt", $hero, $MidTurns)
}

Write-Host "recording $($plan.Count) episodes, $Parallel at a time, into $Dir"

$running = @()
$results = @()
foreach ($entry in $plan) {
    while ($running.Count -ge $Parallel) {
        $finished = Complete-Recording $running[0]
        $running = @($running | Select-Object -Skip 1)
        $results += $finished
        if ($finished.Ok) {
            Write-Host ("  {0,-22} {1,-10} {2,6} steps  {3}" -f `
                $finished.Job.Name, $finished.Job.Hero, $finished.Steps, $finished.Termination)
        } else {
            Write-Host ("  {0,-22} {1,-10} FAILED: {2}" -f $finished.Job.Name, $finished.Job.Hero, $finished.Reason) -ForegroundColor Red
        }
    }
    $running += Start-Recording -Name $entry[0] -Hero $entry[1] -Turns $entry[2] -Seed $entry[0]
}
while ($running.Count -gt 0) {
    $finished = Complete-Recording $running[0]
    $running = @($running | Select-Object -Skip 1)
    $results += $finished
    if ($finished.Ok) {
        Write-Host ("  {0,-22} {1,-10} {2,6} steps  {3}" -f `
            $finished.Job.Name, $finished.Job.Hero, $finished.Steps, $finished.Termination)
    } else {
        Write-Host ("  {0,-22} {1,-10} FAILED: {2}" -f $finished.Job.Name, $finished.Job.Hero, $finished.Reason) -ForegroundColor Red
    }
}

# A run that ended in death rather than a limit, so the corpus covers the case where the hero is gone
# rather than merely stopped. Which seed kills a given hero is a property of the world, so the probes
# all run at once and the first DEATH wins rather than paying for them in sequence.
Write-Host "probing for a death-terminated run (up to ${DeathProbeSeconds}s)"

# Probes write into a scratch directory outside $Dir, and this is the fix rather than another sweep.
#
# Probes are killed rather than waited for, and a killed JVM does not stop instantly: it can still be
# writing when the next phase starts. Writing into the corpus directory meant a probe could drop a file
# in at any point - after the cleanup sweep, even during verification - and the verification phase picks
# up whatever .replay files it finds, so the probe was verified and kept as a corpus member. A name-based
# sweep could not fix this because the file appeared after the sweep. Keeping scratch output out of the
# directory being published makes the failure impossible rather than unlikely.
$probeDir = Join-Path $logDir 'probes'
New-Item -ItemType Directory -Path $probeDir -Force | Out-Null

$probeCount = 12
$probes = @()
for ($i = 0; $i -lt $probeCount; $i++) {
    $probes += Start-Recording -Name "probe-death-$i" -Hero 'WARRIOR' -Turns 200 -Seed "death-probe-$i" -SaveDir $probeDir
}

$deadline = [DateTime]::UtcNow.AddSeconds($DeathProbeSeconds)
$winner = $null
foreach ($probe in $probes) {
    $remaining = [int]([Math]::Max(1, ($deadline - [DateTime]::UtcNow).TotalMilliseconds))
    $probe.Proc.WaitForExit($remaining) | Out-Null
    if (-not $probe.Proc.HasExited) { $probe.Proc.Kill(); continue }
    $out = (Get-Content $probe.Log -Raw -ErrorAction SilentlyContinue)
    if ($out -match 'outcome\s+DEATH') { $winner = $probe; break }
}

if ($winner) {
    # Promoted BEFORE the cleanup sweep below. It used to be after, and the sweep deletes every probe's
    # file - including the winner's - so the move then failed on a file that had just been removed. The
    # script died there with a stray-process problem of its own: the remaining probes were still running
    # and nothing killed them.
    $deathPath = Join-Path $Dir 'warrior-death.replay'
    Copy-Item $winner.Path $deathPath -Force
    $steps = (Get-Content $deathPath | Select-String -Pattern '^[A-Z_]+ ').Count
    Write-Host ("  {0,-22} {1,-10} {2,6} steps  DEATH (seed {3})" -f 'warrior-death', 'WARRIOR', $steps, $winner.Seed)
} else {
    Write-Host "  no seed died within the budget; the corpus has no death recording" -ForegroundColor Yellow
}

# Every probe is killed, and every probe file left in the scratch directory is discarded: a probe named
# "death-probe-7" that survived is not a death recording and would only be misread as one. Nothing here
# needs to be selective, because the winner was already copied out above.
foreach ($probe in $probes) {
    if (-not $probe.Proc.HasExited) {
        $probe.Proc.Kill()
        # Wait for the kill to land. Without this the JVM can still be running when verification starts,
        # which is how a probe file reappeared after the sweep that was supposed to have removed it.
        $probe.Proc.WaitForExit(5000) | Out-Null
    }
}
Remove-Item $probeDir -Recurse -Force -ErrorAction SilentlyContinue

# Three corpus members are not rollout recordings. Each is produced by a command that searches for a
# seed and refuses to write anything else, because a corpus member that cannot witness what it exists
# for is worse than no member: duelist-drop carries the only DROP in SLOT, duelist-throw the only
# recorded press, duelist-death-last a death on the final step. This script cleared the directory
# wholesale and did not rebuild them, so a regeneration quietly dropped a third of the corpus and
# every gate that reads those three reported the wrong thing - 17 of 20 instead of 20 of 20, which
# reads as a regression rather than as a file that was never written.
Write-Host "rebuilding the three fixtures that are not rollouts"
$fixtures = @(
    @{ Name = 'duelist-drop.replay';   Command = 'dropfixture';   Seed = 'DROPFIXTURE' }
    @{ Name = 'duelist-throw.replay';  Command = 'pressfixture';  Seed = 'PRESSFIXTURE' }
)
foreach ($fixture in $fixtures) {
    $log = Join-Path $logDir "fixture-$($fixture.Name).log"
    $work = Join-Path $logDir "fixturework-$($fixture.Name)"
    if (Test-Path $work) { Remove-Item $work -Recurse -Force }
    New-Item -ItemType Directory -Path $work | Out-Null

    $proc = Start-Process -FilePath 'java' -PassThru -NoNewWindow `
        -RedirectStandardOutput $log -RedirectStandardError "$log.err" `
        -ArgumentList @('-cp', $cp, $main, $fixture.Command,
                        '--save', (Join-Path $Dir $fixture.Name),
                        '--out', $work, '--no-color')
    $null = $script:spawned.Add($proc)
    $proc.WaitForExit($PerFileSeconds * 1000) | Out-Null
    if (-not $proc.HasExited) { $proc.Kill() }

    if (Test-Path (Join-Path $Dir $fixture.Name)) {
        Write-Host ("  {0,-24} rebuilt" -f $fixture.Name)
    } else {
        Write-Host ("  {0,-24} NOT REBUILT - see {1}" -f $fixture.Name, $log) -ForegroundColor Red
    }
}

# A death recording, from the same command the death analysis runs, which refuses to write one that
# does not end in DEATH, does not reproduce, or refuses no step at all.
$deathLog = Join-Path $logDir 'fixture-duelist-death-last.log'
$deathWork = Join-Path $logDir 'fixturework-duelist-death-last'
if (Test-Path $deathWork) { Remove-Item $deathWork -Recurse -Force }
New-Item -ItemType Directory -Path $deathWork | Out-Null
$deathProc = Start-Process -FilePath 'java' -PassThru -NoNewWindow `
    -RedirectStandardOutput $deathLog -RedirectStandardError "$deathLog.err" `
    -ArgumentList @('-cp', $cp, $main, 'reprocheck', 'deathfixture')
$null = $script:spawned.Add($deathProc)
$deathProc.WaitForExit($PerFileSeconds * 1000) | Out-Null
if (-not $deathProc.HasExited) { $deathProc.Kill() }

$deathBuilt = Join-Path $module 'out\evidence\duelist-acceptance-fixture.replay'
if (Test-Path $deathBuilt) {
    Move-Item $deathBuilt (Join-Path $Dir 'duelist-death-last.replay') -Force
    Write-Host ("  {0,-24} rebuilt" -f 'duelist-death-last.replay')
} else {
    Write-Host ("  {0,-24} NOT REBUILT - see {1}" -f 'duelist-death-last.replay', $deathLog) -ForegroundColor Red
}

Write-Host "verifying every recording reproduces, $Parallel at a time"

# A recording that does not reproduce is not committed. Leaving it in place would mean the corpus
# fails for a reason unrelated to whatever the next reader is investigating, and the old corpus was
# exactly that: readable, listed by the catalog, and reproducing nothing. Rejected files are kept under
# rejected/ so the failure is inspectable rather than silent.
$files = @(Get-ChildItem $Dir -File -Filter *.replay | Sort-Object Name)
$pending = @()
foreach ($f in $files) {
    $log = Join-Path $logDir "verify-$($f.BaseName).log"
    # --out here for the same reason as in Start-Recording: verification boots a real run and resets
    # it, so it touches the same save files. Seventeen verifiers sharing one work directory would
    # corrupt each other's state and report recordings as broken that are not.
    $work = Join-Path $logDir "verifywork-$($f.BaseName)"
    if (Test-Path $work) { Remove-Item $work -Recurse -Force }
    New-Item -ItemType Directory -Path $work | Out-Null

    $proc = Start-Process -FilePath 'java' -PassThru -NoNewWindow `
        -RedirectStandardOutput $log -RedirectStandardError "$log.err" `
        -ArgumentList @('-cp', $cp, $main, 'verify', $f.FullName, '--out', $work, '--no-color')
    $null = $script:spawned.Add($proc)
    $pending += , [PSCustomObject]@{ File = $f; Proc = $proc; Log = $log }
}

$bad = @()
$verified = @()
while ($pending.Count -gt 0) {
    $item = $pending[0]
    $pending = @($pending | Select-Object -Skip 1)

    $item.Proc.WaitForExit($PerFileSeconds * 1000) | Out-Null
    if (-not $item.Proc.HasExited) {
        $item.Proc.Kill()
        $bad += $item.File.Name
        continue
    }

    $out = (Get-Content $item.Log -Raw -ErrorAction SilentlyContinue)
    if ($out -match '\[OK\]') {
        $steps = (Select-String -InputObject $out -Pattern 'steps=(\d+)').Matches.Groups[1].Value
        $verified += , [PSCustomObject]@{ Name = $item.File.Name; Steps = [int]$steps }
    } else {
        $bad += $item.File.Name
        if (-not (Test-Path $rejected)) { New-Item -ItemType Directory -Path $rejected | Out-Null }
        Move-Item $item.File.FullName (Join-Path $rejected $item.File.Name) -Force
    }
}

# Verification is what decides the corpus, so it reports the same shape the recording phase did.
foreach ($v in ($verified | Sort-Object Name)) {
    Write-Host ("  {0,-24} reproduces ({1} steps)" -f $v.Name, $v.Steps)
}
foreach ($name in $bad) {
    Write-Host ("  {0,-24} DOES NOT REPRODUCE - moved to rejected/" -f $name) -ForegroundColor Red
}

$stopwatch.Stop()

# Counted from what verification actually proved, not from what is sitting in the directory.
#
# Counting files made the summary claim a corpus of 20 when 16 had been verified: the extra four were
# probe scratch files that had been swept up and verified like corpus members. Nothing was wrong with
# them individually, so no check complained - the summary was simply describing a different set of
# files than the one it had verified. "All reproduce" has to mean all of what is being reported.
$kept = @($verified).Count
$onDisk = (Get-ChildItem $Dir -File -Filter *.replay).Count
if ($onDisk -ne $kept) {
    Write-Host "  WARNING: $onDisk files on disk but $kept verified; the corpus is not what was reported" -ForegroundColor Red
}

$heroes_covered = @($verified | ForEach-Object { ($_.Name -split '-')[0] } | Sort-Object -Unique)

Write-Host ""
Write-Host "corpus rebuilt: $kept recordings, all reproduce, in $([Math]::Round($stopwatch.Elapsed.TotalSeconds, 1))s"
Write-Host "  heroes covered: $($heroes_covered -join ', ')"
Write-Host "  slowest recording: $((($verified | Sort-Object Steps -Descending | Select-Object -First 1).Steps)) steps"

if ($stopwatch.Elapsed.TotalSeconds -gt $BudgetSeconds) {
    Write-Host ("  WARNING: over the ${BudgetSeconds}s budget by $([Math]::Round($stopwatch.Elapsed.TotalSeconds - $BudgetSeconds, 1))s") -ForegroundColor Yellow
}

if ($bad.Count -gt 0) {
    Write-Host "$($bad.Count) recording(s) rejected: $($bad -join ', ')" -ForegroundColor Yellow
    Pop-Location
    exit 1
}

Pop-Location
exit 0